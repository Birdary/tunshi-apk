#==============================================================================
# ■ Window_ItemCategory
#------------------------------------------------------------------------------
# 　物品画面和商店画面中，显示装备、所持物品等项目列表的窗口。
#==============================================================================

class Window_ItemCategory < Window_Command
  #--------------------------------------------------------------------------
  # ● 定义实例变量
  #--------------------------------------------------------------------------
  attr_reader   :item_window
  #--------------------------------------------------------------------------
  # ● 初始化对象
  #--------------------------------------------------------------------------
  def initialize
    super(0, 0)
    self.opacity = 0
    self.height = 160
    contents.font.size = 12 + $game_variables[300]
  end
  #--------------------------------------------------------------------------
  # ● 获取窗口的宽度
  #--------------------------------------------------------------------------
  def window_width
    160
  end
  #--------------------------------------------------------------------------
  # ● 获取列数
  #--------------------------------------------------------------------------
  def col_max
    return 1
  end

  def item_max
    return 3
  end

  #--------------------------------------------------------------------------
  # ● 更新画面
  #--------------------------------------------------------------------------
  def update
    super
    @item_window.category = current_symbol if @item_window
  end
  #--------------------------------------------------------------------------
  # ● 生成指令列表
  #--------------------------------------------------------------------------
  def make_command_list
    add_command("",     :item)
    add_command("",   :weapon)
    add_command("",    :armor)
    #add_command(Vocab::key_item, :key_item)
  end
  #--------------------------------------------------------------------------
  # ● 设置物品窗口
  #--------------------------------------------------------------------------
  def item_window=(item_window)
    @item_window = item_window
    update
  end

  def item_rect(index)
    rect = Rect.new
    rect.width = 64
    rect.height = 26
    case index
    when 0
      y = 10
    when 1 
      y = 50
    when 2 
      y = 90
    end
    rect.x = 10
    rect.y = y
    rect
  end
end
